export type FerramentaCatalogo = { chave: string; nome: string; categoria: string; categoriaId: string; pais: string; finalidadePadrao: string };

export const slugFerramenta = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

